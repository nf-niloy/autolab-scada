import assert from 'node:assert/strict';
globalThis.location={hostname:'127.0.0.1',port:'8000',protocol:'http:',host:'127.0.0.1:8000'};
const {validateLiveRecipe,localBridgeAvailable,LiveController}=await import('../src/live-controller.js');
assert.equal(localBridgeAvailable(),true);
assert.equal(validateLiveRecipe({repeats:1,steps:[{duration:5,motor:true,fan:false}]}),null);
assert.match(validateLiveRecipe({repeats:1,steps:[{duration:180,motor:true,fan:false}]}),/120/);
assert.match(validateLiveRecipe({repeats:1,steps:[{duration:5,motor:true,fan:true}]}),/simultaneous/);
assert.match(validateLiveRecipe({repeats:1,steps:Array.from({length:9},()=>({duration:3}))}),/1–8/);
const live=new LiveController();
live.enabled=true;
live.apply({serial_connected:true,telemetry_fresh:true,telemetry:{sequence:100,uptime_ms:100000,ds18b20_c:30.5,mlx90614_c:30.6,motor:1,fan:0,mode:'MANUAL',step:0,cycle:0,fault:'NONE',recorded_at:'2026-10-11T06:00:00+00:00'},active_run:null,recent_events:[{id:1,time:'2026-10-11T06:00:00+00:00',raw:'EVENT,100000,MANUAL_OUTPUT'}]});
assert.equal(live.state.contact,30.5);
assert.equal(live.ready,true);
assert.equal(live.state.motor,true);
assert.equal(live.state.events.length,1);
live.apply({serial_connected:false,telemetry_fresh:false,telemetry:null,active_run:null,recent_events:[]});
assert.equal(live.ready,false);
assert.equal(live.state.contact,null);
console.log('Frontend adapter unit tests PASSED');
